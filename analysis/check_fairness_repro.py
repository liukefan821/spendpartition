"""Execute the real harness twice and compare every CSV byte-for-byte. No simulation."""

import argparse
import csv
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from fairness import ROOT, aggregate, load_trace

FILES = ("fairness_trace.csv", "fairness_agents.csv", "fairness.csv")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(command, log):
    print("Running:", " ".join(map(str, command)), flush=True)
    result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    log.write_text(result.stdout)
    if result.returncode:
        print(result.stdout, end="")
        raise subprocess.CalledProcessError(result.returncode, command)
    print(result.stdout.strip().splitlines()[-1], flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--forge", default=shutil.which("forge") or str(Path.home() / ".foundry/bin/forge"))
    args = parser.parse_args()
    audit = ROOT / "results/fairness_audit"
    audit.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="sc6109-fairness-") as directory:
        first = Path(directory)
        for iteration in (1, 2):
            run([args.forge, "test", "--match-contract", "^FairnessTest$", "-vv"], audit / f"repeat-{iteration}-forge.log")
            run([sys.executable, str(ROOT / "analysis/fairness.py")], audit / f"repeat-{iteration}-analysis.log")
            if iteration == 1:
                for name in FILES:
                    shutil.copyfile(ROOT / "results" / name, first / name)
        hashes = {}
        for name in FILES:
            path = ROOT / "results" / name
            if (first / name).read_bytes() != path.read_bytes():
                raise ValueError(f"same-seed CSV differs byte-for-byte: {name}")
            hashes[name] = digest(path)
            print(f"IDENTICAL {name}: {hashes[name]}")
    groups = load_trace(ROOT / "results/fairness_trace.csv")
    agents, summaries = aggregate(groups)
    # Compare the independent existing RhoSweep output, generated by the full suite.
    rho_path = ROOT / "results/rho_sweep.csv"
    if not rho_path.exists():
        raise FileNotFoundError("run forge test (or RhoSweepTest) before this baseline cross-check")
    with rho_path.open(newline="") as f:
        original = list(csv.DictReader(f))
    adversarial = {(a["rho_num"], a["agent"]): a for a in agents if a["scenario"] == "adversarial_first"}
    if len(original) != 33:
        raise ValueError("existing RhoSweep must contain 33 rows")
    for r in original:
        a = adversarial[(int(r["rho_num"]), r["agent"])]
        for old, new in (("reservation", "reservation"), ("demanded", "demanded"), ("granted", "granted"),
                         ("rejected_requests", "budget_rejected_requests")):
            if int(r[old]) != a[new]:
                raise ValueError(f"baseline RhoSweep mismatch: {r['rho_num']}, {r['agent']}, {old}")
    environment = json.loads((audit / "environment.json").read_text())
    for name, expected in environment["protected_sha256"].items():
        if digest(ROOT / name) != expected:
            raise ValueError(f"protected file changed: {name}")
    artifact = json.loads((ROOT / "out/SpendPartition.sol/SpendPartition.json").read_text())
    for key, field in (("creation_bytecode_sha256", "bytecode"), ("runtime_bytecode_template_sha256", "deployedBytecode")):
        if hashlib.sha256(artifact[field]["object"].encode()).hexdigest() != environment[key]:
            raise ValueError(f"SpendPartition {field} changed")
    import matplotlib
    environment["analysis_python"] = sys.version
    environment["matplotlib"] = matplotlib.__version__
    (audit / "environment.json").write_text(json.dumps(environment, indent=2) + "\n")
    evidence = dict(seed=0x5EED, trace_rows=sum(map(len, groups.values())), agent_rows=len(agents),
                    summary_rows=len(summaries), csv_sha256=hashes, csv_runs_byte_identical=True,
                    original_rho_sweep_rows_matched=33, protected_files_unchanged=True,
                    creation_and_runtime_bytecode_unchanged=True)
    (audit / "verification.json").write_text(json.dumps(evidence, indent=2) + "\n")
    print("PASS: 352 attempts; 66 agent rows; 22 configurations; original RhoSweep matches; protected files and bytecode unchanged")


if __name__ == "__main__":
    main()
